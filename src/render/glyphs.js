function glyph(art) {
  const rows = art.trim().split('\n').map(row => row.trim());
  const width = rows[0].length;
  if (width > 14 || rows.length > 14 || rows.some(row => row.length !== width)) throw Error('Icon art must fit a regular 14×14 grid');
  const x = Math.floor((GLYPH_SIZE - width) / 2), y = Math.floor((GLYPH_SIZE - rows.length) / 2);
  return Array.from({ length: GLYPH_SIZE }, (_, i) => i < y || i >= y + rows.length
    ? '.'.repeat(GLYPH_SIZE) : '.'.repeat(x) + rows[i - y] + '.'.repeat(GLYPH_SIZE - width - x));
}


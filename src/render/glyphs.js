export function drawGlyph(g, rows, palette = GLYPH_PALETTE) {
  // Horizontal runs keep placement integer-aligned without canvas paths or AA.
  for (let y = 0; y < rows.length; y++) for (let x = 0; x < rows[y].length;) {
    const ch = rows[y][x], start = x++;
    while (x < rows[y].length && rows[y][x] === ch) x++;
    if (ch === '.') continue;
    g.fillStyle = palette[ch];
    g.fillRect(start, y, x - start, 1);
  }
}
